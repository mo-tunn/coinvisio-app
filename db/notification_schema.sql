-- 2. Notification Preferences
CREATE TABLE IF NOT EXISTS public.notification_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL, -- References Supabase Auth User ID
    coin_symbol TEXT, -- If NULL, applies to Global settings
    preference_type TEXT, -- e.g., 'all', 'high_severity_only', 'none', or specific notification_type code
    is_enabled BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, coin_symbol, preference_type)
);

-- 3. Notifications Table
CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    notification_type_id BIGINT REFERENCES public.notification_types(id),
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    coin_symbol TEXT, -- Optional, if related to a specific coin
    severity TEXT CHECK (severity IN ('low', 'medium', 'high')) DEFAULT 'low',
    confidence NUMERIC(3,2) DEFAULT 1.00, -- 0.00 to 1.00
    payload JSONB DEFAULT '{}'::JSONB, -- Structured data for mobile/frontend
    is_read BOOLEAN DEFAULT FALSE,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON public.notifications(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_unread ON public.notifications(user_id) WHERE is_read = FALSE;
CREATE INDEX IF NOT EXISTS idx_notifications_dedup ON public.notifications(user_id, coin_symbol, notification_type_id, created_at DESC);

-- 4. Utility Functions

-- Clean up old notifications
CREATE OR REPLACE FUNCTION public.cleanup_notifications()
RETURNS void AS $$
BEGIN
    -- Delete read notifications older than 24 hours
    DELETE FROM public.notifications
    WHERE is_read = TRUE AND read_at < NOW() - INTERVAL '24 hours';

    -- Delete unread notifications older than 7 days
    DELETE FROM public.notifications
    WHERE is_read = FALSE AND created_at < NOW() - INTERVAL '7 days';
END;
$$ LANGUAGE plpgsql;

-- Get unread count efficiently
CREATE OR REPLACE FUNCTION public.get_unread_notification_count(p_user_id UUID)
RETURNS INTEGER AS $$
BEGIN
    RETURN (SELECT COUNT(*) FROM public.notifications WHERE user_id = p_user_id AND is_read = FALSE);
END;
$$ LANGUAGE plpgsql;
