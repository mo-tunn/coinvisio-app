-- 1. Crypto Prices (OHLCV Data)
CREATE TABLE IF NOT EXISTS public.crypto_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol TEXT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL,
    open NUMERIC,
    high NUMERIC,
    low NUMERIC,
    close NUMERIC,
    volume NUMERIC,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Unique index for upserts
CREATE UNIQUE INDEX IF NOT EXISTS idx_crypto_prices_symbol_date 
ON public.crypto_prices (symbol, recorded_at);


-- 2. Coin Anomalies
CREATE TABLE IF NOT EXISTS public.coin_anomalies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol TEXT NOT NULL,
    anomaly_type TEXT,
    anomaly_score NUMERIC,
    price_at_detection NUMERIC,
    detected_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 3. Recommendations
CREATE TABLE IF NOT EXISTS public.recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_profile TEXT NOT NULL,
    coins JSONB, -- Stores the list of recommended coins
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 4. Market Regime
CREATE TABLE IF NOT EXISTS public.market_regime (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regime_label TEXT,
    cluster_id INTEGER,
    avg_volatility NUMERIC,
    avg_return NUMERIC,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 5. Smart Signals
CREATE TABLE IF NOT EXISTS public.smart_signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol TEXT NOT NULL,
    term TEXT, -- Short, Mid, Long
    signal_type TEXT, -- LONG, SHORT, NEUTRAL
    entry_price NUMERIC,
    target_price NUMERIC,
    stop_loss NUMERIC,
    confidence_score NUMERIC,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 6. Model Performance (Backtesting/Evaluation)
CREATE TABLE IF NOT EXISTS public.model_performance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_id BIGINT REFERENCES public.smart_signals(id),
    symbol TEXT,
    result TEXT, -- SUCCESS, FAILURE
    reward INTEGER, -- 1 or -1
    evaluated_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 7. Model Weights (RL Optimization)
CREATE TABLE IF NOT EXISTS public.model_weights (
    symbol TEXT PRIMARY KEY, -- Using symbol as PK for easy upsert
    accuracy NUMERIC DEFAULT 0,
    is_active BOOLEAN DEFAULT TRUE,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 8. Daily Insights (LLM Reports)
CREATE TABLE IF NOT EXISTS public.daily_insights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insight_text TEXT,
    sentiment TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

